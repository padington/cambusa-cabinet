    # drawer translation. This does not simulate multi-link hinges or rails.
    base=[p for p in b['parts'] if p['group'] in ['body','profile','back','pegboard']]
    for angle in range(0,111,10):
        view=transformed(b,angle,accessories=False)
        doors=[p for p in view if p['group']=='door']
        samples+=1
        for p in doors:
            for q in base:
                v=collision_volume(p['mesh'],q['mesh'])
                if v>.2:hits.append(dict(test='door',angle=angle,a=p['name'],b=q['name'],volume_mm3=round(v,2)))
    for i in [0,1]:
        for travel in range(0,281,20):
            view=transformed(b,100 if inside else 0,travel,i,accessories=False)
            moving=[p for p in view if p['group']=='drawer' and p['drawer_id']==i]
            obstacles=base+[p for p in view if p['group']=='door' or (p['group']=='drawer' and p['drawer_id']!=i)]
            samples+=1
            for p in moving:
                for q in obstacles:
                    v=collision_volume(p['mesh'],q['mesh'])
                    if v>.2:hits.append(dict(test='drawer',drawer=i,travel_mm=travel,a=p['name'],b=q['name'],volume_mm3=round(v,2)))
    motion.append(dict(id=b['id'],sampled_positions=samples,major_panel_intersections=hits,scope='Sampled ideal movement only; actual fitting kinematics and strength not validated.'))
